// Minimum acceptable accuracy for the deterministic (rule-based) analyzer. The
// gate catches a regression in root-cause inference; it sits just below the
// current score so the harness has to actually keep working, not merely exist.
const (
	minOverallAccuracy     = 0.85
	minRootServiceAccuracy = 0.85
	minPlaybookAccuracy    = 0.95
)

// TestDeterministicCausalAccuracy is the CI gate: it scores the rule-based
// fallback (no API key, no network) against the labelled fixtures and fails the
// build if accuracy regresses below the thresholds.
func TestDeterministicCausalAccuracy(t *testing.T) {
	sc := Evaluate(context.Background(), &NoopAnalyzer{}, EvalFixtures())

	t.Logf("rule-based causal accuracy: overall=%.1f%% rootService=%.1f%% playbook=%.1f%% confidence=%.1f%% narrative=%.1f%% (n=%d)",
		sc.Overall*100, sc.RootServiceAccuracy*100, sc.PlaybookAccuracy*100,
		sc.ConfidenceAccuracy*100, sc.NarrativeAccuracy*100, sc.Count)

	for _, r := range sc.Results {
		if !r.passed() {
			t.Logf("  miss %q: rootSvc=%v(got %q) playbook=%v(got %q) conf=%v(got %.2f) narrative=%v err=%q",
				r.Name, r.RootServiceOK, r.GotRootSvc, r.PlaybookOK, r.GotPlaybook,
				r.ConfidenceOK, r.GotConfidence, r.NarrativeOK, r.Err)
		}
	}

	if sc.Count == 0 {
		t.Fatal("no fixtures evaluated")
	}
	if sc.Overall < minOverallAccuracy {
		t.Errorf("overall accuracy %.3f below threshold %.2f", sc.Overall, minOverallAccuracy)
	}
	if sc.RootServiceAccuracy < minRootServiceAccuracy {
		t.Errorf("root-service accuracy %.3f below threshold %.2f", sc.RootServiceAccuracy, minRootServiceAccuracy)
	}
	if sc.PlaybookAccuracy < minPlaybookAccuracy {
		t.Errorf("playbook accuracy %.3f below threshold %.2f", sc.PlaybookAccuracy, minPlaybookAccuracy)
	}
}

// TestRootServiceHelper guards the DAG-root identification independently of the
// full scorer.
func TestRootServiceHelper(t *testing.T) {
	sc := Evaluate(context.Background(), &NoopAnalyzer{}, EvalFixtures())
	byName := map[string]FixtureResult{}
	for _, r := range sc.Results {
		byName[r.Name] = r
	}
	// The diamond converges on a single source; the helper must find it.
	if got := byName["diamond-converging-root"].GotRootSvc; got != "db" {
		t.Errorf("diamond root: got %q, want db", got)
	}
	// The hard case is expected to miss (the true root is an undeclared dependency).
	if byName["hidden-root-undeclared-dependency"].RootServiceOK {
		t.Error("hidden-root fixture unexpectedly passed — the harness should reflect this known deterministic limitation")
	}
}

// TestWriteCausalEvalReport regenerates CAUSAL_EVAL.md. It is gated on an env var
// so a normal `go test` run doesn't mutate the repo; run it with
// CAUSAL_EVAL_REPORT=1 to refresh the published scorecard.
func TestWriteCausalEvalReport(t *testing.T) {
	if os.Getenv("CAUSAL_EVAL_REPORT") == "" {
		t.Skip("set CAUSAL_EVAL_REPORT=1 to regenerate CAUSAL_EVAL.md")
	}
	sc := Evaluate(context.Background(), &NoopAnalyzer{}, EvalFixtures())
	// shared/causal → repo root is two levels up.
	path := "../../CAUSAL_EVAL.md"
	if err := os.WriteFile(path, []byte(renderReport(sc)), 0o644); err != nil {
		t.Fatalf("write report: %v", err)
	}
	t.Logf("wrote %s", path)
}

func renderReport(sc Scorecard) string {
	var b strings.Builder
	pct := func(f float64) string { return fmt.Sprintf("%.1f%%", f*100) }

	b.WriteString("# Causal-AI Evaluation Scorecard\n\n")
	b.WriteString("_ROAD_TO_100 · F0.5 — measured accuracy of root-cause inference. Generated by\n")
	b.WriteString("`shared/causal` (`CAUSAL_EVAL_REPORT=1 go test ./causal/...`); do not edit by hand._\n\n")
	b.WriteString(fmt.Sprintf("_Generated: %s_\n\n", time.Now().UTC().Format(time.RFC3339)))

	b.WriteString("## Why this exists\n\n")
	b.WriteString("\"AI RCA\" is only a feature if its accuracy is measured. This scores an analyzer\n")
	b.WriteString("against labelled incidents whose true root cause is known. The deterministic\n")
	b.WriteString("(rule-based) analyzer is scored in CI with no API key or network, and the build\n")
	b.WriteString("fails if accuracy regresses. LLM providers implement the same `Analyzer`\n")
	b.WriteString("interface and can be scored with the same harness when a key is present.\n\n")

	b.WriteString(fmt.Sprintf("## Analyzer: `%s` — overall **%s** (n=%d)\n\n", sc.Analyzer, pct(sc.Overall), sc.Count))
	b.WriteString("| Dimension | Accuracy |\n| --- | ---: |\n")
	b.WriteString(fmt.Sprintf("| Root-cause service identified | %s |\n", pct(sc.RootServiceAccuracy)))
	b.WriteString(fmt.Sprintf("| Remediation playbook correct | %s |\n", pct(sc.PlaybookAccuracy)))
	b.WriteString(fmt.Sprintf("| Confidence at/above floor | %s |\n", pct(sc.ConfidenceAccuracy)))
	b.WriteString(fmt.Sprintf("| Narrative mentions root cause | %s |\n", pct(sc.NarrativeAccuracy)))
	b.WriteString(fmt.Sprintf("| **All dimensions (overall)** | **%s** |\n\n", pct(sc.Overall)))

	b.WriteString("## Per-incident results\n\n")
	b.WriteString("| Incident | Root svc | Playbook | Confidence | Narrative | Pass |\n")
	b.WriteString("| --- | :---: | :---: | :---: | :---: | :---: |\n")
	mark := func(ok bool) string {
		if ok {
			return "✅"
		}
		return "❌"
	}
	for _, r := range sc.Results {
		b.WriteString(fmt.Sprintf("| `%s` | %s | %s | %s | %s | %s |\n",
			r.Name, mark(r.RootServiceOK), mark(r.PlaybookOK), mark(r.ConfidenceOK), mark(r.NarrativeOK), mark(r.passed())))
	}
	b.WriteString("\n")

	b.WriteString("## Known limitation (honest headroom)\n\n")
	b.WriteString("The `hidden-root-undeclared-dependency` fixture is expected to **miss**: the true\n")
	b.WriteString("root cause sits behind a dependency edge that was never declared, so the\n")
	b.WriteString("deterministic graph walk blames the nearest declared cause. This is exactly the\n")
	b.WriteString("gap an LLM narrative that reads the alert messages can close — the reason the\n")
	b.WriteString("LLM providers exist above the rule-based fallback. Keeping the miss in the set is\n")
	b.WriteString("what makes the headline number trustworthy rather than a fixture designed to pass.\n")
	return b.String()
}
